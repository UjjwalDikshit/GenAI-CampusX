
from dotenv import load_dotenv
from langchain_core.tools import tool, InjectedToolArg
from langchain_core.messages import HumanMessage, ToolMessage
from langchain_google_genai import ChatGoogleGenerativeAI
from typing import Annotated
import requests
import os

load_dotenv()

model = ChatGoogleGenerativeAI(model="gemini-2.5-flash")


@tool
def get_conversation_factor(
    base_currency: str,
    target_currency: str
) -> float:
    """This function fetches the currency conversion factor between
    a given base currency and a target currency."""

    api_key = os.getenv("EXCHANGE_RATE_API_KEY")

    url = (
        f"https://v6.exchangerate-api.com/v6/{api_key}"
        f"/pair/{base_currency}/{target_currency}"
    )

    response = requests.get(url, timeout=10)
    response.raise_for_status()
    data = response.json()

    if data.get("result") != "success":
        raise ValueError(f"API error: {data}")

    # Return only the conversation rate, not the entire JSON response
    return float(data["conversion_rate"])


@tool
def convert(
    base_currency_value: float,
    conversation_rate: Annotated[float, InjectedToolArg]
) -> float:
    # InjectedToolArg means:
    # LLM does not need to provide the conversation_rate argument.
    # The developer will provide this value after executing the
    # get_conversation_factor tool.
    """Convert the base currency value using the conversation rate."""

    return base_currency_value * conversation_rate


# Bind both tools to the LLM
llm_with_tools = model.bind_tools(
    [get_conversation_factor, convert]
)

messages = [
    HumanMessage(
        content="Convert today's 1000 USD into Indian rupees."
    )
]

# Ask the LLM which tools it needs to call
ai_message = llm_with_tools.invoke(messages)
messages.append(ai_message)

print("Tool calls:", ai_message.tool_calls)

# This variable will store the conversation rate fetched from the API
conversation_rate = None

# Execute the tools manually
# We need this when one tool depends on the output of another tool.
for tool_call in ai_message.tool_calls:

    # Execute the 1st tool and fetch the current conversation rate
    if tool_call["name"] == "get_conversation_factor":

        tool_message1 = get_conversation_factor.invoke(
            tool_call["args"]
        )

        # Store the conversation rate returned by the API
        conversation_rate = float(tool_message1)

        # Send the tool output back to the LLM conversation
        messages.append(
            ToolMessage(
                content=str(tool_message1),
                tool_call_id=tool_call["id"]
            )
        )

    # Execute the 2nd tool using the conversation rate fetched above
    elif tool_call["name"] == "convert":

        # Check whether we have fetched the conversation rate yet
        if conversation_rate is None:
            raise ValueError(
                "Fetch the conversation rate before calling convert."
            )

        # Inject the conversation rate into the tool arguments.
        # LLM provides base_currency_value, but the developer
        # provides conversation_rate after executing the 1st tool.
        tool_call["args"]["conversation_rate"] = conversation_rate

        tool_message2 = convert.invoke(tool_call["args"])

        # Send the conversion result back to the LLM
        messages.append(
            ToolMessage(
                content=str(tool_message2),
                tool_call_id=tool_call["id"]
            )
        )

# Pass the entire conversation, including both tool outputs, to the LLM
final_response = llm_with_tools.invoke(messages)
messages.append(final_response)

# Print the final response generated by the LLM
print("Final response:", final_response.content)
